class Command(BaseCommand):
    help = "Создаёт демо-данные: 2–3 темы по 10+ вопросов."

    def handle(self, *args, **options):
        for title, description, questions in DEMO_TOPICS:
            topic, _ = Topic.objects.get_or_create(
                title=title, defaults={"description": description}
            )
            if description and not topic.description:
                topic.description = description
                topic.save()
            for text, option_list, correct_index in questions:
                Question.objects.update_or_create(
                    topic=topic,
                    text=text,
                    defaults={
                        "options": option_list,
                        "correct_index": correct_index,
                        "is_active": True,
                    },
                )
            self.stdout.write(self.style.SUCCESS(f"Тема '{title}': {len(questions)} вопросов"))
        self.stdout.write(
            self.style.SUCCESS(
                f"Готово. Тем: {Topic.objects.count()}, "
                f"вопросов: {Question.objects.count()}"
            )
        )
